//! Embedded 8x8 bitmap font (public-domain `font8x8_basic` glyphs) + atlas baking.
//!
//! The font is baked once at startup into a 128x64 `R8Unorm` coverage texture (16 columns x 8 rows
//! of 8x8 glyphs, ASCII 0x00..0x80). `glyph_uv` is a pure arithmetic lookup, so text geometry can be
//! emitted on the CPU (overlay.rs) without touching the GPU; renderer.rs owns the texture/sampler.
//!
//! Bit convention: each glyph is 8 rows top-to-bottom; in a row byte, bit 0 (LSB) is the LEFT pixel.

/// Glyph cell size in texels.
pub const GLYPH: u32 = 8;
/// Atlas grid: 16 columns x 8 rows of cells.
pub const COLS: u32 = 16;
pub const ROWS: u32 = 8;
pub const ATLAS_W: u32 = COLS * GLYPH; // 128
pub const ATLAS_H: u32 = ROWS * GLYPH; // 64

/// (u0, v0, u1, v1) of character `c`'s cell in the atlas, in [0,1] texture space.
#[inline]
pub fn glyph_uv(c: u8) -> [f32; 4] {
    let col = (c as u32) % COLS;
    let row = (c as u32) / COLS;
    let u0 = (col * GLYPH) as f32 / ATLAS_W as f32;
    let v0 = (row * GLYPH) as f32 / ATLAS_H as f32;
    let du = GLYPH as f32 / ATLAS_W as f32;
    let dv = GLYPH as f32 / ATLAS_H as f32;
    [u0, v0, u0 + du, v0 + dv]
}

/// Bake the font into a single-channel (R8) coverage image, row-major `y*ATLAS_W + x`,
/// 255 where a glyph pixel is set, else 0.
pub fn bake_r8() -> Vec<u8> {
    let mut img = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
    for c in 0..128usize {
        let col = (c as u32) % COLS;
        let row = (c as u32) / COLS;
        let glyph = &FONT8X8[c];
        for (py, &bits) in glyph.iter().enumerate() {
            for px in 0..8u32 {
                if (bits >> px) & 1 == 1 {
                    let ax = col * GLYPH + px;
                    let ay = row * GLYPH + py as u32;
                    img[(ay * ATLAS_W + ax) as usize] = 255;
                }
            }
        }
    }
    img
}

